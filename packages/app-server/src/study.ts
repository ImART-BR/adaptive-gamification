export const NEW_PER_DAY = 10;
export const MAX_DUE_PER_DAY = 100;
export const SESSION_GAP_MS = 30 * 60_000;

// ---- sessions ---------------------------------------------------------------------------------------------

/** A session is a visit; it closes after 30 minutes without activity. Ids are generated by the server. */
export function touchSession(db: Db, userId: number, now: number): string {
  const last = one<{ id: string; last_seen: number }>(db, 'SELECT id, last_seen FROM sessions WHERE user_id = ? ORDER BY last_seen DESC LIMIT 1', userId);
  if (last && now - last.last_seen < SESSION_GAP_MS) {
    run(db, 'UPDATE sessions SET last_seen = ? WHERE id = ?', now, last.id);
    return last.id;
  }
  const id = `s_${randomBytes(6).toString('hex')}`;
  run(db, 'INSERT INTO sessions (id, user_id, started_at, last_seen) VALUES (?, ?, ?, ?)', id, userId, now, now);
  return id;
}

// ---- daily queue -----------------------------------------------------------------------------------------

function reviewsOnDay(db: Db, userId: number, day: number): number {
  return one<{ n: number }>(db, 'SELECT COUNT(*) AS n FROM reviews WHERE user_id = ? AND day = ?', userId, day)?.n ?? 0;
}

/**
 * Snapshot of the day's queue (due cards + up to NEW_PER_DAY new ones), taken on the first access of the day.
 * The "target behavior" of the app is finishing this queue: outcome = done / total.
 * If the snapshot was empty and nothing was reviewed yet, it is rebuilt (the user may have just added a deck).
 */
export function ensureDailyQueue(db: Db, userId: number, now: number, sessionId: string): { day: number; total: number; done: number } {
  const day = dayNumber(now);
  const st = one<{ queue_total: number; first_session_id: string | null }>(db, 'SELECT queue_total, first_session_id FROM daily_state WHERE user_id = ? AND day = ?', userId, day);
  if (st && !(st.queue_total === 0 && reviewsOnDay(db, userId, day) === 0)) {
    const done = one<{ n: number }>(db, 'SELECT COUNT(*) AS n FROM daily_queue WHERE user_id = ? AND day = ? AND done = 1', userId, day)?.n ?? 0;
    return { day, total: st.queue_total, done };
  }
  return tx(db, () => {
    run(db, 'DELETE FROM daily_queue WHERE user_id = ? AND day = ?', userId, day);
    const due = all<{ card_id: number }>(
      db,
      `SELECT cs.card_id FROM card_state cs
         JOIN cards c ON c.id = cs.card_id
         JOIN library l ON l.deck_id = c.deck_id AND l.user_id = cs.user_id
        WHERE cs.user_id = ? AND cs.due <= ? ORDER BY cs.due, cs.card_id LIMIT ?`,
      userId,
      day,
      MAX_DUE_PER_DAY,
    );
    // New cards are spread across the library's decks (round-robin, in library order), so every deck gets a share
    // of the day's NEW_PER_DAY instead of the first deck taking all of it.
    const fresh = all<{ id: number }>(
      db,
      `SELECT id FROM (
         SELECT c.id, l.added_at, ROW_NUMBER() OVER (PARTITION BY c.deck_id ORDER BY c.id) AS rn
           FROM cards c
           JOIN library l ON l.deck_id = c.deck_id AND l.user_id = ?
           LEFT JOIN card_state cs ON cs.card_id = c.id AND cs.user_id = ?
          WHERE cs.card_id IS NULL
       ) WHERE rn <= ? ORDER BY rn, added_at, id LIMIT ?`,
      userId,
      userId,
      NEW_PER_DAY,
      NEW_PER_DAY,
    );
    const ids = [...due.map((r) => r.card_id), ...fresh.map((r) => r.id)];
    for (const id of ids) run(db, 'INSERT OR IGNORE INTO daily_queue (user_id, day, card_id, done) VALUES (?, ?, ?, 0)', userId, day, id);
    run(db, 'INSERT INTO daily_state (user_id, day, queue_total, first_session_id) VALUES (?, ?, ?, ?) ON CONFLICT(user_id, day) DO UPDATE SET queue_total = excluded.queue_total', userId, day, ids.length, st?.first_session_id ?? sessionId);
    return { day, total: ids.length, done: 0 };
  });
}

/**
 * The decks that have cards in today's queue, in library order, with how many are still pending. The queue itself
 * (and therefore the day's outcome) always covers all decks; choosing decks only filters what is shown for study.
 */
export function queueDecks(db: Db, userId: number, now: number, sessionId: string) {
  const q = ensureDailyQueue(db, userId, now, sessionId);
  return all<{ id: number; title: string; total: number; pending: number; fresh: number }>(
    db,
    `SELECT d.id, d.title, COUNT(*) AS total,
            SUM(CASE WHEN dq.done = 0 THEN 1 ELSE 0 END) AS pending,
            SUM(CASE WHEN dq.done = 0 AND cs.card_id IS NULL THEN 1 ELSE 0 END) AS fresh
       FROM daily_queue dq
       JOIN cards c ON c.id = dq.card_id
       JOIN decks d ON d.id = c.deck_id
       LEFT JOIN card_state cs ON cs.card_id = c.id AND cs.user_id = dq.user_id
       LEFT JOIN library l ON l.deck_id = d.id AND l.user_id = dq.user_id
      WHERE dq.user_id = ? AND dq.day = ?
      GROUP BY d.id ORDER BY MIN(l.added_at), d.id`,
    userId,
    q.day,
  ).map((r) => ({ deckId: r.id, title: r.title, total: r.total, pending: r.pending, fresh: r.fresh }));
}

/** Cards still to study today. `deckIds` (optional) restricts them to the decks the user chose; ids outside the queue are ignored. */
export function nextCards(db: Db, userId: number, now: number, sessionId: string, limit = 20, deckIds?: number[]) {
  const q = ensureDailyQueue(db, userId, now, sessionId);
  const startOfDay = (q.day * 86_400_000) + 180 * 60_000; // local midnight in ms (UTC-3)
  const filter = deckIds && deckIds.length > 0 ? ` AND c.deck_id IN (${deckIds.map(() => '?').join(',')})` : '';
  const extra = deckIds && deckIds.length > 0 ? deckIds : [];
  const cards = all<{ id: number; front: string; back: string; deck_id: number; deck_title: string; phase: string | null }>(
    db,
    `SELECT c.id, c.front, c.back, c.deck_id, d.title AS deck_title, cs.phase
       FROM daily_queue dq
       JOIN cards c ON c.id = dq.card_id
       JOIN decks d ON d.id = c.deck_id
       LEFT JOIN card_state cs ON cs.card_id = c.id AND cs.user_id = dq.user_id
       LEFT JOIN library l ON l.deck_id = d.id AND l.user_id = dq.user_id
      WHERE dq.user_id = ? AND dq.day = ? AND dq.done = 0${filter}
      ORDER BY (cs.last_review IS NOT NULL AND cs.last_review >= ?) ASC, l.added_at, d.id, c.id
      LIMIT ?`,
    userId,
    q.day,
    ...extra,
    startOfDay,
    limit,
  );
  const sel = one<{ total: number; done: number | null }>(
    db,
    `SELECT COUNT(*) AS total, SUM(dq.done) AS done FROM daily_queue dq JOIN cards c ON c.id = dq.card_id
      WHERE dq.user_id = ? AND dq.day = ?${filter}`,
    userId,
    q.day,
    ...extra,
  ) ?? { total: 0, done: 0 };
  return {
    total: q.total,
    done: q.done,
    selected: { total: sel.total, done: sel.done ?? 0 },
    cards: cards.map((c) => ({ id: c.id, front: c.front, back: c.back, deckId: c.deck_id, deckTitle: c.deck_title, isNew: c.phase === null })),
  };
}

// ---- progress queries ----------------------------------------------------------------------------------------

function addPoints(db: Db, userId: number, now: number, points: number, reason: string): void {
  grantPoints(db, userId, now, points, reason);
}

function bestRunToday(db: Db, userId: number, day: number): number {
  const grades = all<{ grade: number }>(db, 'SELECT grade FROM reviews WHERE user_id = ? AND day = ? ORDER BY id', userId, day);
  let best = 0;
  let cur = 0;
  for (const g of grades) {
    cur = g.grade >= 2 ? cur + 1 : 0;
    best = Math.max(best, cur);
  }
  return best;
}

function todayStats(db: Db, userId: number, day: number): TodayStats {
  const st = one<{ queue_total: number }>(db, 'SELECT queue_total FROM daily_state WHERE user_id = ? AND day = ?', userId, day);
  const done = one<{ n: number }>(db, 'SELECT COUNT(*) AS n FROM daily_queue WHERE user_id = ? AND day = ? AND done = 1', userId, day)?.n ?? 0;
  return { reviewsToday: reviewsOnDay(db, userId, day), queueDone: done, queueTotal: st?.queue_total ?? 0, bestRun: bestRunToday(db, userId, day) };
}

export function masteryByDeck(db: Db, userId: number) {
  return all<{ id: number; title: string; total: number; seen: number; mature: number }>(
    db,
    `SELECT d.id, d.title,
            (SELECT COUNT(*) FROM cards c WHERE c.deck_id = d.id) AS total,
            (SELECT COUNT(*) FROM cards c JOIN card_state s ON s.card_id = c.id AND s.user_id = l.user_id WHERE c.deck_id = d.id) AS seen,
            (SELECT COUNT(*) FROM cards c JOIN card_state s ON s.card_id = c.id AND s.user_id = l.user_id WHERE c.deck_id = d.id AND s.interval >= ?) AS mature
       FROM library l JOIN decks d ON d.id = l.deck_id WHERE l.user_id = ? ORDER BY l.added_at, d.id`,
    MATURE_INTERVAL,
    userId,
  ).map((r) => ({ deckId: r.id, title: r.title, cardCount: r.total, seen: r.seen, mature: r.mature, masteryPct: r.total ? Math.round((100 * r.mature) / r.total) : 0 }));
}

function streakDays(db: Db, userId: number, today: number): number {
  const days = all<{ day: number }>(db, 'SELECT DISTINCT day FROM reviews WHERE user_id = ? ORDER BY day DESC', userId).map((r) => r.day);
  if (days.length === 0) return 0;
  let expected = days[0] === today || days[0] === today - 1 ? days[0]! : -1;
  if (expected < 0) return 0;
  let n = 0;
  for (const d of days) {
    if (d === expected) {
      n += 1;
      expected -= 1;
    } else if (d < expected) break;
  }
  return n;
}

function userStats(db: Db, userId: number, today: number): UserStats {
  const totalReviews = one<{ n: number }>(db, 'SELECT COUNT(*) AS n FROM reviews WHERE user_id = ?', userId)?.n ?? 0;
  const decksCreated = one<{ n: number }>(db, 'SELECT COUNT(*) AS n FROM decks WHERE owner_id = ? AND source_deck_id IS NULL', userId)?.n ?? 0;
  const remixes = one<{ n: number }>(db, 'SELECT COUNT(*) AS n FROM decks WHERE owner_id = ? AND source_deck_id IS NOT NULL', userId)?.n ?? 0;
  const decksExplored = one<{ n: number }>(db, 'SELECT COUNT(*) AS n FROM library l JOIN decks d ON d.id = l.deck_id WHERE l.user_id = ? AND (d.owner_id IS NULL OR d.owner_id <> ?)', userId, userId)?.n ?? 0;
  const maxMasteryPct = Math.max(0, ...masteryByDeck(db, userId).filter((m) => m.cardCount >= 5).map((m) => m.masteryPct));
  const perfectDays = one<{ n: number }>(
    db,
    `SELECT COUNT(*) AS n FROM daily_state s
      WHERE s.user_id = ? AND s.queue_total >= 5
        AND (SELECT COUNT(*) FROM daily_queue q WHERE q.user_id = s.user_id AND q.day = s.day AND q.done = 1) = s.queue_total`,
    userId,
  )?.n ?? 0;
  return { totalReviews, streakDays: streakDays(db, userId, today), decksCreated, decksExplored, remixes, maxMasteryPct, perfectDays, level: levelFromPoints(totalPoints(db, userId)), ...socialStats(db, userId) };
}

/** Grants completed daily challenges and unlocked achievements (once each) and their point bonuses. */
function evaluateProgress(db: Db, userId: number, now: number) {
  const day = dayNumber(now);
  const challengesDone: { key: string; title: string; reward: number }[] = [];
  const newAchievements: { key: string; title: string; bonus: number }[] = [];
  const t = todayStats(db, userId, day);
  for (const c of DAILY_CHALLENGES) {
    if (c.progress(t) >= c.target(t) && c.target(t) > 0 && !one(db, 'SELECT 1 AS x FROM challenge_claims WHERE user_id = ? AND key = ? AND day = ?', userId, c.key, day)) {
      run(db, 'INSERT INTO challenge_claims (user_id, key, day, claimed_at) VALUES (?, ?, ?, ?)', userId, c.key, day, now);
      addPoints(db, userId, now, c.reward, `challenge:${c.key}`);
      challengesDone.push({ key: c.key, title: c.title, reward: c.reward });
    }
  }
  for (let pass = 0; pass < 3; pass++) {
    const stats = userStats(db, userId, day);
    let any = false;
    for (const a of ACHIEVEMENTS) {
      if (a.earned(stats) && !one(db, 'SELECT 1 AS x FROM achievements WHERE user_id = ? AND key = ?', userId, a.key)) {
        run(db, 'INSERT INTO achievements (user_id, key, unlocked_at) VALUES (?, ?, ?)', userId, a.key, now);
        addPoints(db, userId, now, a.bonus, `achievement:${a.key}`);
        logActivity(db, userId, 'achievement', { title: a.title }, now);
        newAchievements.push({ key: a.key, title: a.title, bonus: a.bonus });
        any = true;
      }
    }
    if (!any) break;
  }
  return { challengesDone, newAchievements };
}

/** Called after library changes (create/remix/explore) so "creator", "remixer" and "explorer" unlock. */
export function refreshProgress(db: Db, userId: number, now: number) {
  return tx(db, () => evaluateProgress(db, userId, now));
}

// ---- review ---------------------------------------------------------------------------------------------------

export function answerReview(db: Db, userId: number, now: number, sessionId: string, cardId: unknown, gradeIn: unknown) {
  if (!Number.isInteger(cardId)) throw new HttpError(400, 'cardId inválido');
  if (typeof gradeIn !== 'number' || ![0, 1, 2, 3].includes(gradeIn)) throw new HttpError(400, 'nota inválida (0 a 3)');
  const grade = gradeIn as Grade;
  const q = ensureDailyQueue(db, userId, now, sessionId);
  const inQueue = one<{ done: number }>(db, 'SELECT done FROM daily_queue WHERE user_id = ? AND day = ? AND card_id = ?', userId, q.day, cardId as number);
  if (!inQueue) throw new HttpError(400, 'este cartão não está na fila de hoje');
  const card = one<{ id: number; deck_id: number }>(db, 'SELECT id, deck_id FROM cards WHERE id = ?', cardId as number);
  if (!card) throw new HttpError(404, 'cartão não encontrado');

  return tx(db, () => {
    const levelBefore = levelFromPoints(totalPoints(db, userId));
    const row = one<{ ease: number; interval: number; due: number; reps: number; lapses: number; phase: CardState['phase'] }>(db, 'SELECT ease, interval, due, reps, lapses, phase FROM card_state WHERE user_id = ? AND card_id = ?', userId, card.id);
    const prev: CardState = row ?? newCardState(q.day);
    const next = schedule(prev, grade, q.day);
    run(
      db,
      `INSERT INTO card_state (user_id, card_id, ease, interval, due, reps, lapses, phase, last_review) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
       ON CONFLICT(user_id, card_id) DO UPDATE SET ease = excluded.ease, interval = excluded.interval, due = excluded.due, reps = excluded.reps, lapses = excluded.lapses, phase = excluded.phase, last_review = excluded.last_review`,
      userId, card.id, next.ease, next.interval, next.due, next.reps, next.lapses, next.phase, now,
    );
    run(db, 'INSERT INTO reviews (user_id, card_id, deck_id, at, day, grade, prev_interval, new_interval, session_id) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)', userId, card.id, card.deck_id, now, q.day, grade, prev.interval, next.interval, sessionId);
    addPoints(db, userId, now, POINTS_PER_GRADE[grade], 'review');

    let done = q.done;
    if (grade >= 1 && inQueue.done === 0) {
      run(db, 'UPDATE daily_queue SET done = 1 WHERE user_id = ? AND day = ? AND card_id = ?', userId, q.day, card.id);
      done += 1;
      // Target behavior: fraction of the day's queue finished. Credited to the first session of the day.
      const first = one<{ first_session_id: string | null }>(db, 'SELECT first_session_id FROM daily_state WHERE user_id = ? AND day = ?', userId, q.day)?.first_session_id ?? sessionId;
      run(db, "INSERT INTO events (user_id, session_id, type, at, kind, value) VALUES (?, ?, 'outcome', ?, 'target', ?)", userId, first, now, q.total > 0 ? done / q.total : 0);
      if (q.total > 0 && done === q.total) logActivity(db, userId, 'queue_done', {}, now);
    }
    const progress = evaluateProgress(db, userId, now);
    const pairBonus = grade >= 1 ? checkPairBonus(db, userId, now) : 0;
    const pointsAfter = totalPoints(db, userId);
    return {
      grade,
      nextIntervalDays: next.interval,
      pointsGained: POINTS_PER_GRADE[grade],
      queueDone: done,
      queueTotal: q.total,
      levelBefore,
      levelAfter: levelFromPoints(pointsAfter),
      totalPoints: pointsAfter,
      challengesDone: progress.challengesDone,
      newAchievements: progress.newAchievements,
      pairBonus,
    };
  });
}

// ---- screens ---------------------------------------------------------------------------------------------------

export function leaderboard(db: Db, userId: number, now: number) {
  const weekStart = weekStartDay(dayNumber(now));
  const rows = all<{ id: number; nickname: string; avatar: string; frame: string; pts: number }>(
    db,
    `SELECT u.id, u.nickname, u.avatar, u.frame, SUM(p.points) AS pts
       FROM point_events p JOIN users u ON u.id = p.user_id
      WHERE p.day >= ? GROUP BY u.id HAVING pts > 0 ORDER BY pts DESC, u.id`,
    weekStart,
  );
  const ranked = rows.map((r, i) => ({ rank: i + 1, nickname: r.nickname, avatar: r.avatar, frame: r.frame, points: r.pts, me: r.id === userId }));
  return { top: ranked.slice(0, 10), me: ranked.find((r) => r.me) ?? null, participants: ranked.length };
}

export function userRow(db: Db, userId: number) {
  return one<{ id: number; nickname: string; avatar: string; theme: string; frame: string; consented_at: number | null }>(db, 'SELECT id, nickname, avatar, theme, frame, consented_at FROM users WHERE id = ?', userId);
}

export function home(db: Db, userId: number, now: number, sessionId: string) {
  const day = dayNumber(now);
  const q = ensureDailyQueue(db, userId, now, sessionId);
  const points = totalPoints(db, userId);
  const lv = levelProgress(points);
  const t = todayStats(db, userId, day);
  const claimed = new Set(all<{ key: string }>(db, 'SELECT key FROM challenge_claims WHERE user_id = ? AND day = ?', userId, day).map((r) => r.key));
  const unlocked = new Map(all<{ key: string; unlocked_at: number }>(db, 'SELECT key, unlocked_at FROM achievements WHERE user_id = ?', userId).map((r) => [r.key, r.unlocked_at]));
  const user = userRow(db, userId)!;
  return {
    user: { nickname: user.nickname, avatar: user.avatar, theme: user.theme, frame: user.frame },
    today: { queueTotal: q.total, queueDone: q.done, reviewsToday: t.reviewsToday, decks: queueDecks(db, userId, now, sessionId).filter((d) => d.pending > 0) },
    points: { total: points, weekly: leaderboard(db, userId, now).me?.points ?? 0 },
    level: { level: lv.level, into: lv.into, needed: lv.needed },
    mastery: masteryByDeck(db, userId),
    challenges: DAILY_CHALLENGES.map((c) => ({ key: c.key, title: c.title, reward: c.reward, progress: Math.min(c.progress(t), c.target(t)), target: c.target(t), claimed: claimed.has(c.key) })),
    achievements: ACHIEVEMENTS.map((a) => ({ key: a.key, title: a.title, description: a.description, bonus: a.bonus, unlockedAt: unlocked.get(a.key) ?? null })),
    leaderboard: leaderboard(db, userId, now),
    cosmetics: {
      avatars: AVATARS,
      themes: THEMES.map((x) => ({ key: x.key, label: x.label, level: x.level, unlocked: lv.level >= x.level })),
      frames: FRAMES.map((x) => ({ key: x.key, label: x.label, level: x.level, unlocked: lv.level >= x.level })),
    },
    streakDays: streakDays(db, userId, day),
  };
}

export function updateProfile(db: Db, userId: number, input: { nickname?: unknown; avatar?: unknown; theme?: unknown; frame?: unknown }) {
  const level = levelFromPoints(totalPoints(db, userId));
  const cur = userRow(db, userId)!;
  let nickname = cur.nickname;
  if (input.nickname !== undefined) {
    if (typeof input.nickname !== 'string') throw new HttpError(400, 'apelido inválido');
    nickname = input.nickname.trim();
    if (nickname.length < 2 || nickname.length > 24) throw new HttpError(400, 'o apelido precisa ter de 2 a 24 caracteres');
  }
  let avatar = cur.avatar;
  if (input.avatar !== undefined) {
    if (!(AVATARS as readonly unknown[]).includes(input.avatar)) throw new HttpError(400, 'avatar inválido');
    avatar = input.avatar as string;
  }
  let theme = cur.theme;
  if (input.theme !== undefined) {
    const th = THEMES.find((x) => x.key === input.theme);
    if (!th) throw new HttpError(400, 'tema inválido');
    if (level < th.level) throw new HttpError(403, `tema desbloqueado no nível ${th.level}`);
    theme = th.key;
  }
  let frame = cur.frame;
  if (input.frame !== undefined) {
    const fr = FRAMES.find((x) => x.key === input.frame);
    if (!fr) throw new HttpError(400, 'moldura inválida');
    if (level < fr.level) throw new HttpError(403, `moldura desbloqueada no nível ${fr.level}`);
    frame = fr.key;
  }
  run(db, 'UPDATE users SET nickname = ?, avatar = ?, theme = ?, frame = ? WHERE id = ?', nickname, avatar, theme, frame, userId);
  return { nickname, avatar, theme, frame };
}
